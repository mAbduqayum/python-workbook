sides = int(input())

if sides == 3:
    print("triangle")
elif sides == 4:
    print("quadrilateral")
elif sides == 5:
    print("pentagon")
elif sides == 6:
    print("hexagon")
elif sides == 7:
    print("heptagon")
elif sides == 8:
    print("octagon")
elif sides == 9:
    print("nonagon")
elif sides == 10:
    print("decagon")
else:
    print("invalid number of sides")
